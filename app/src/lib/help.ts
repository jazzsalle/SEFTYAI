/** 지금 보는 화면의 도움말 — 모르는 길이면 통합 탐색 것(개발서버 screenHelpOf) */
export function screenHelpOf(pathname: string): ScreenHelp {
  return SCREEN_HELPS.find(([p]) => pathname.startsWith(p))?.[1] ?? EXPLORE;
}

/** 검색 — 제목이 걸리면 그 묶음을 통째로, 줄만 걸리면 걸린 줄만(개발서버 searchSections) */
export function searchSections(query: string, sections: HelpSection[] = HELP_SECTIONS): HelpSection[] {
  const needle = query.trim().toLowerCase();
  if (needle === "") return sections;
  const found: HelpSection[] = [];
  for (const section of sections) {
    if (section.title.toLowerCase().includes(needle)) {
      found.push(section);
      continue;
    }
    const lines = section.lines.filter((line) => line.toLowerCase().includes(needle));
    if (lines.length > 0) found.push({ ...section, lines });
  }
  return found;
}

