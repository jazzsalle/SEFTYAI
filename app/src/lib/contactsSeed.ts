export function seedBundle(orgId: string): Bundle {
  if (orgId === "busan") {
    const j = busanSeed as unknown as Bundle;
    return { units: j.units, contacts: j.contacts, groups: j.groups };
  }
  const conf = SEEDS[orgId];
  if (!conf) return { units: [], contacts: [], groups: [] };
  const units: Unit[] = [];
  const contacts: Contact[] = [];
  let nu = 0, nc = 0;
  const walk = (list: Seed[], parentId: string | null) =>
    list.forEach((s, i) => {
      const id = `${orgId}-u${++nu}`;
      units.push({ id, orgId, parentId, name: s.name, kind: s.kind, sort: i });
      (s.people ?? []).forEach(([title, duty, office], k) => {
        const n = nc++;
        contacts.push({
          id: `${orgId}-c${nc}`, orgId, unitId: id, title, duty: duty ?? "", office: office ?? "", sort: k,
          name: SURNAMES[(n * 7 + conf.base) % SURNAMES.length] + GIVEN[(n * 3 + conf.base) % GIVEN.length],
          phone: `010-0000-${conf.base + nc}`, email: `${orgId}${nc}@example.go.kr`,
        });
      });
      if (s.children) walk(s.children, id);
    });
  walk(conf.tree, null);
  const unitName = new Map(units.map((u) => [u.id, u.name]));
  // 소속 조직 이름으로 고름 (지휘부 = 대책본부 직속 인원)
  const groups: Group[] = conf.groups.map((g, i) => ({
    id: `${orgId}-g${i + 1}`, orgId, name: g.name, sort: i,
    memberIds: contacts.filter((c) => g.match.some((m) => (unitName.get(c.unitId) ?? "").includes(m))).map((c) => c.id),
  }));
  return { units, contacts, groups };
}
